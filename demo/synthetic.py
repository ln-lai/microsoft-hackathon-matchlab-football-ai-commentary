"""Original procedural football scenarios; never reads real match/training data.

Coordinates follow the existing model contract: metres from the top-left corner,
x in [0, 105], y in [0, 68]. These trajectories are demonstration fixtures, not
observations from an actual match and not a benchmark of real-world accuracy.
"""
from dataclasses import dataclass

import numpy as np


FPS = 25
PITCH = {"length": 105, "width": 68, "coordinate_origin": "top_left"}
PLAYER_IDS = tuple([f"Home_{i}" for i in range(1, 12)] + [f"Away_{i}" for i in range(1, 12)])
TEAMS = np.array([0] * 11 + [1] * 11 + [2], dtype=np.int64)


@dataclass(frozen=True)
class Match:
    id: str
    title: str
    timestamps: np.ndarray
    positions: np.ndarray
    available: np.ndarray
    events: tuple
    player_ids: tuple = PLAYER_IDS

    @property
    def duration_s(self):
        return float(self.timestamps[-1] - self.timestamps[0])

    def summary(self):
        return {"id": self.id, "title": self.title, "duration_s": self.duration_s,
                "fps": FPS, "source": "synthetic"}

    def public_payload(self):
        # Explicit nulls preserve missingness without emitting invalid JSON NaN.
        visible = [[xy.tolist() if ok else None for xy, ok in zip(frame, mask)]
                   for frame, mask in zip(self.positions, self.available)]
        return {**self.summary(), "pitch": PITCH,
                "players": [{"id": identity, "number": i % 11 + 1,
                             "team": i // 11, "name": f'{"Home" if i < 11 else "Away"} {i % 11 + 1:02d}'}
                            for i, identity in enumerate(self.player_ids)],
                "timestamps": self.timestamps.tolist(), "positions": visible,
                "available": self.available.tolist(), "events": list(self.events),
                "provenance": "Original analytic trajectories generated by demo/synthetic.py; no real match data.",
                "prediction_window": {"first_anchor_frame": 98,
                                      "last_anchor_frame": len(self.timestamps) - 26,
                                      "input_samples": 50, "input_hz": 12.5,
                                      "horizon_s": 1.0}}


def _step(t, start, duration):
    """Smooth transition with zero velocity at both ends."""
    u = np.clip((t - start) / duration, 0.0, 1.0)
    return u * u * (3.0 - 2.0 * u)


def make_matches():
    """Build three deterministic 40-second scenes with distinct motion patterns."""
    t = np.arange(1001, dtype=np.float64) / FPS
    home = np.array([[7, 34], [25, 9], [24, 25], [24, 43], [25, 59],
                     [42, 14], [40, 34], [42, 54], [58, 12], [60, 34], [58, 56]], dtype=float)
    away = np.array([[98, 34], [78, 11], [77, 26], [77, 42], [78, 57],
                     [63, 16], [62, 34], [63, 52], [46, 15], [44, 34], [46, 53]], dtype=float)
    base = np.concatenate((home, away), axis=0)
    specs = [
        ("space-run", "Run into space", ((5.0, "Attack builds on the right"),
                                         (12.0, "Forward accelerates into the channel"),
                                         (23.0, "Defence recovers its shape"))),
        ("defensive-shift", "Defensive shift", ((5.0, "Possession moves across the pitch"),
                                               (14.0, "Defensive block shifts laterally"),
                                               (26.0, "Play returns to the near side"))),
        ("transition", "Transition in motion", ((5.0, "Teams move into attacking shape"),
                                               (15.0, "Direction of play reverses"),
                                               (27.0, "Defence regroups"))),
    ]
    matches = {}
    for scenario, title, event_specs in specs:
        xy = np.repeat(base[None], len(t), axis=0)
        # Low-amplitude movement keeps even off-ball players active and smooth.
        for j in range(22):
            scale = 0.4 if j in (0, 11) else 1.0
            xy[:, j, 0] += scale * (1.1 * np.sin(t * .29 + j * .7))
            xy[:, j, 1] += scale * (1.4 * np.sin(t * .23 + j * .9))
        if scenario == "space-run":
            build = 5 * _step(t, 3, 10) - 4 * _step(t, 25, 10)
            xy[:, 1:11, 0] += build[:, None]
            xy[:, 12:22, 0] += (3 * _step(t, 8, 9))[:, None]
            run = 17 * _step(t, 10, 7) - 13 * _step(t, 24, 9)
            xy[:, 8, 0] += run
            xy[:, 8, 1] += 9 * _step(t, 10, 7) - 5 * _step(t, 27, 8)
            ball = xy[:, 5].copy()
            fraction = _step(t, 11.5, 2.5) - _step(t, 23, 3)
            ball = ball * (1 - fraction[:, None]) + xy[:, 8] * fraction[:, None]
        elif scenario == "defensive-shift":
            lateral = 7 * np.sin((t - 5) * .17)
            xy[:, 1:11, 1] += lateral[:, None]
            xy[:, 12:22, 1] += (6 * np.sin((t - 7) * .17))[:, None]
            xy[:, 1:11, 0] += (4 * np.sin(t * .12))[:, None]
            ball = np.column_stack((54 + 6 * np.sin(t * .19), 34 + 23 * np.sin((t - 5) * .17)))
        else:
            attack = 9 * _step(t, 3, 10) - 19 * _step(t, 15, 10) + 5 * _step(t, 29, 8)
            xy[:, 1:11, 0] += attack[:, None]
            xy[:, 12:22, 0] += (8 * _step(t, 4, 10) - 20 * _step(t, 16, 10))[:, None]
            xy[:, 9, 1] += 8 * _step(t, 16, 7)
            xy[:, 20, 0] -= 9 * _step(t, 17, 7)
            blend = _step(t, 15, 1.8)
            ball = xy[:, 6] * (1 - blend[:, None]) + xy[:, 20] * blend[:, None]
        ball += [0.6, 0.45]
        positions = np.concatenate((xy, ball[:, None, :]), axis=1)
        assert ((positions >= 0) & (positions <= np.array([105, 68]))).all()
        available = np.ones((len(t), 23), dtype=bool)
        # One explicit dropout demonstrates mask handling without a synthetic height.
        available[(t >= 20) & (t < 20.4), 22] = False
        positions[~available] = np.nan
        for array in (positions, available):
            array.setflags(write=False)
        events = tuple({"time_s": time_s, "title": event_title} for time_s, event_title in event_specs)
        matches[scenario] = Match(scenario, title, t.copy(), positions, available, events)
    return matches
